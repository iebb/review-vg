import { spawn } from "node:child_process";
import { readFile, rename, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const projectDirectory = resolve(fileURLToPath(new URL("../", import.meta.url)));
const defaultOutput = resolve(projectDirectory, "public/review-data.js");
const defaultQuery = resolve(projectDirectory, "scripts/public-reviews.sql");
const maximumCommandOutputBytes = 50 * 1024 * 1024;

function text(value, field, { nullable = false } = {}) {
  if (nullable && value === null) return null;
  if (typeof value !== "string") throw new Error(`${field} must be a string`);
  const normalized = value.trim();
  if (!normalized) throw new Error(`${field} must not be empty`);
  return normalized;
}

function optionalText(value, field) {
  if (value === null || value === undefined || value === "") return null;
  return text(value, field);
}

function flag(value, field) {
  const number = Number(value);
  if (number !== 0 && number !== 1) throw new Error(`${field} must be 0 or 1`);
  return number === 1;
}

function timestamp(value, field, { nullable = false } = {}) {
  if (nullable && (value === null || value === undefined || value === "")) return null;
  const normalized = text(value, field);
  if (!Number.isFinite(Date.parse(normalized))) throw new Error(`${field} is not a valid timestamp`);
  return normalized;
}

function iconUrl(value) {
  const normalized = optionalText(value, "app_icon_url");
  if (!normalized) return null;
  let parsed;
  try {
    parsed = new URL(normalized);
  } catch {
    throw new Error("app_icon_url must be a valid URL");
  }
  if (parsed.protocol !== "https:") throw new Error("app_icon_url must use HTTPS");
  return parsed.href;
}

function publicEvent(row) {
  if (!row || typeof row !== "object" || Array.isArray(row)) {
    throw new Error("Every D1 result must be an object");
  }

  const submissionId = text(row.submission_id, "submission_id");
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(submissionId)) {
    throw new Error(`Invalid submission_id: ${submissionId}`);
  }
  const status = text(row.status, "status");
  if (status !== "issue" && status !== "success") {
    throw new Error(`Invalid status for ${submissionId}`);
  }
  const appStoreId = text(String(row.app_store_id ?? ""), "app_store_id");
  if (!/^\d+$/.test(appStoreId)) throw new Error(`Invalid app_store_id for ${submissionId}`);

  return {
    submissionId,
    appName: optionalText(row.app_name, "app_name"),
    hasApproved: flag(row.has_approved, "has_approved"),
    platform: text(row.platform, "platform"),
    appStoreId,
    appIconUrl: iconUrl(row.app_icon_url),
    appCategory: optionalText(row.app_category, "app_category"),
    appVersion: optionalText(row.app_version, "app_version"),
    status,
    submittedAt: timestamp(row.submitted_at, "submitted_at", { nullable: true }),
    occurredAt: timestamp(row.latest_event_at, "latest_event_at"),
    guidelineCode: status === "issue" ? optionalText(row.guideline_code, "guideline_code") : null,
    guidelineTitle: status === "issue" ? optionalText(row.guideline_title, "guideline_title") : null,
  };
}

export function createPublicSnapshot(rows, generatedAt = new Date().toISOString()) {
  if (!Array.isArray(rows)) throw new Error("D1 results must be an array");
  if (rows.length === 0) throw new Error("Refusing to publish an empty review snapshot");
  timestamp(generatedAt, "generatedAt");

  const submissionIds = new Set();
  const events = [];
  const leaderboardEvents = [];
  for (const row of rows) {
    const event = publicEvent(row);
    if (submissionIds.has(event.submissionId)) {
      throw new Error(`Duplicate submission_id: ${event.submissionId}`);
    }
    submissionIds.add(event.submissionId);
    leaderboardEvents.push(event);
    if (flag(row.in_timeline, "in_timeline")) events.push(event);
  }

  return { generatedAt, events, leaderboardEvents };
}

export function parseWranglerResult(value) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error("Wrangler returned an unexpected D1 response");
  }
  const failed = value.find((entry) => entry?.success !== true);
  if (failed) throw new Error("The D1 snapshot query did not succeed");
  const resultSets = value.map((entry) => entry?.results).filter(Array.isArray);
  if (resultSets.length !== 1) throw new Error("Expected exactly one D1 result set");
  return resultSets[0];
}

export function serializeSnapshot(snapshot) {
  const json = JSON.stringify(snapshot, null, 2)
    .replaceAll("<", "\\u003c")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
  return `/* Generated by scripts/build-static-data.mjs. Do not edit. */\nwindow.ReviewData = Object.freeze(${json});\n`;
}

async function runWrangler({ local }) {
  const executable = process.platform === "win32" ? "npx.cmd" : "npx";
  const query = await readFile(defaultQuery, "utf8");
  const argumentsList = [
    "wrangler",
    "d1",
    "execute",
    "review-vg",
    local ? "--local" : "--remote",
    "--command",
    query,
    "--json",
  ];

  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(executable, argumentsList, {
      cwd: projectDirectory,
      env: process.env,
      stdio: ["ignore", "pipe", "pipe"],
    });
    const stdout = [];
    const stderr = [];
    let outputBytes = 0;

    const collect = (target) => (chunk) => {
      outputBytes += chunk.length;
      if (outputBytes > maximumCommandOutputBytes) {
        child.kill("SIGTERM");
        rejectPromise(new Error("Wrangler output exceeded the 50 MB safety limit"));
        return;
      }
      target.push(chunk);
    };
    child.stdout.on("data", collect(stdout));
    child.stderr.on("data", collect(stderr));
    child.once("error", rejectPromise);
    child.once("close", (code) => {
      if (code !== 0) {
        const diagnostic = Buffer.concat([...stdout, ...stderr]).toString("utf8").trim().slice(-2000);
        rejectPromise(new Error(`Wrangler exited with code ${code}${diagnostic ? `: ${diagnostic}` : ""}`));
        return;
      }
      try {
        resolvePromise(JSON.parse(Buffer.concat(stdout).toString("utf8")));
      } catch {
        rejectPromise(new Error("Wrangler did not return valid JSON"));
      }
    });
  });
}

function argumentsFrom(argv) {
  const options = { input: null, local: false, output: defaultOutput };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--local") {
      options.local = true;
    } else if (argument === "--input" || argument === "--output") {
      const value = argv[index + 1];
      if (!value) throw new Error(`${argument} requires a path`);
      options[argument.slice(2)] = resolve(process.cwd(), value);
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }
  if (options.input && options.local) throw new Error("--input and --local cannot be combined");
  return options;
}

export async function buildStaticData(options) {
  const wranglerResult = options.input
    ? JSON.parse(await readFile(options.input, "utf8"))
    : await runWrangler({ local: options.local });
  const snapshot = createPublicSnapshot(parseWranglerResult(wranglerResult));
  const temporaryOutput = `${options.output}.${process.pid}.tmp`;
  await writeFile(temporaryOutput, serializeSnapshot(snapshot), "utf8");
  await rename(temporaryOutput, options.output);
  return {
    output: basename(options.output),
    timelineEvents: snapshot.events.length,
    leaderboardEvents: snapshot.leaderboardEvents.length,
  };
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : null;
if (invokedPath === import.meta.url) {
  try {
    const result = await buildStaticData(argumentsFrom(process.argv.slice(2)));
    console.log(`Built ${result.output}: ${result.timelineEvents} timeline events, ${result.leaderboardEvents} all-time events.`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : "Static data build failed");
    process.exitCode = 1;
  }
}
